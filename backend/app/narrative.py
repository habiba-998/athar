def _n(env: Environment, aid: str, lang: str) -> str:
    a = env.asset(aid)
    return (a.name_ar or a.name) if lang == "ar" else a.name


def _list(items: list[str], lang: str, limit: int = 6) -> str:
    sep = "، " if lang == "ar" else ", "
    shown = items[:limit]
    more = len(items) - len(shown)
    tail = (f" +{more}" if more > 0 else "")
    return sep.join(shown) + tail


def action_label(env: Environment, action: dict[str, Any], lang: str) -> str:
    rid = action.get("relationship_id")
    if rid:
        rel = next(r for r in env.relationships if r.id == rid)
        subj = f"{_n(env, rel.source, lang)} → {_n(env, rel.target, lang)}"
    else:
        subj = _n(env, action["asset_id"], lang)
    return f"{ACTION[lang][action['kind']]}: {subj}"


def confidence_label(strong_share: float, stability: str | None) -> tuple[str, list[str]]:
    """Heuristic confidence in a recommendation (NOT a probability): evidence strength of the affected paths, and how
    stable the recommendation is when the scoring assumptions are perturbed (only if the sensitivity run exists)."""
    reasons = ["evidence_strong" if strong_share >= 0.6 else ("evidence_mixed" if strong_share >= 0.25 else "evidence_weak")]
    if stability is None:
        reasons.append("stability_not_assessed")
        return ("low" if strong_share < 0.25 else "medium"), reasons          # never "high" without a sensitivity run
    reasons.append(f"stability_{stability}")
    if strong_share < 0.25 or stability == "sensitive":
        return "low", reasons
    if strong_share >= 0.6 and stability == "stable":
        return "high", reasons
    return "medium", reasons


def _conf_reason(code: str, lang: str) -> str:
    t = {
        "evidence_strong": ("most affected paths rest on validated or observed evidence", "معظم المسارات المتأثرة تستند إلى أدلة مؤكَّدة أو مرصودة"),
        "evidence_mixed": ("the affected paths mix stronger and weaker evidence", "المسارات المتأثرة تجمع بين أدلة أقوى وأضعف"),
        "evidence_weak": ("most affected paths rest on inferred or theoretical evidence", "معظم المسارات المتأثرة تستند إلى أدلة مستنتَجة أو نظرية"),
        "stability_stable": ("the recommendation stays near the top when the scoring weights are varied", "تبقى التوصية في المراتب الأولى عند تغيير أوزان التقييم"),
        "stability_moderate": ("its rank moves moderately when the scoring weights are varied", "تتحرك رتبتها بشكل معتدل عند تغيير أوزان التقييم"),
        "stability_sensitive": ("its rank changes a lot when the scoring weights are varied", "تتغير رتبتها كثيرًا عند تغيير أوزان التقييم"),
        "stability_not_assessed": ("sensitivity to the scoring weights has not been run yet", "لم يُجرَ تحليل الحساسية لأوزان التقييم بعد"),
    }[code]
    return t[1] if lang == "ar" else t[0]


def _context(env: Environment, analysis: dict[str, Any], rec_action: dict[str, Any], stability: str | None) -> dict[str, Any]:
    action = SimulationRequest.model_validate({"actions": [rec_action]}).actions[0]
    res = simulate(env, [action], baseline=analysis)
    op = res["operational_impact"]
    business = service_impact(env, op["affected_relationships"])
    b_paths = {p["id"]: p for p in res["before_paths"]}
    affected_ids = res["paths_eliminated"] + res["paths_mitigated"]
    ev = {"validated": 0, "observed": 0, "inferred": 0, "theoretical": 0}
    sources: set[str] = set()
    for pid in affected_ids:
        p = b_paths[pid]
        ev[p["classification"]] += 1
        sources.update(s["evidence_source"] for s in p["steps"])
    n_aff = len(affected_ids)
    strong = (ev["validated"] + ev["observed"]) / n_aff if n_aff else 0.0
    level, reasons = confidence_label(strong, stability)
    changed = {i["relationship_id"] for i in op["affected_relationships"]}
    through = sum(1 for p in res["before_paths"] if changed & set(p["relationship_ids"]))
    after = res["after"]
    return {"res": res, "op": op, "business": business, "ev": ev, "sources": sorted(sources), "affected_paths": n_aff,
            "paths_through": through, "confidence": level, "confidence_reasons": reasons, "strong_share": round(strong, 3),
            "after": after, "before": res["before"], "remaining": res["residual_risks"][:3], "action": rec_action}


def recommendation_explanation(env: Environment, analysis: dict[str, Any], rec: dict[str, Any],
                               stability: str | None = None) -> dict[str, Any]:
    """The nine answers in both languages plus the structured facts they were built from."""
    c = _context(env, analysis, rec["action"], stability)
    out: dict[str, Any] = {"id": rec["id"], "confidence": {"level": c["confidence"], "reasons": c["confidence_reasons"],
                                                         "strong_evidence_share": c["strong_share"], "is_probability": False},
                           "facts": {"affected_paths": c["affected_paths"], "evidence": c["ev"], "sources": c["sources"],
                                     "paths_before": c["before"]["attack_paths"], "paths_after": c["after"]["attack_paths"],
                                     "posture_before": c["before"]["posture_score"], "posture_after": c["after"]["posture_score"],
                                     "impact_level": c["op"]["level"], "reversible": c["op"]["fully_reversible"],
                                     "business_impact_index": c["business"]["business_impact_index"]},
                           "questions": []}
    answers = {lang: _answers(env, c, rec, lang) for lang in ("en", "ar")}
    for key, (q_en, q_ar) in QUESTIONS.items():
        out["questions"].append({"key": key, "question": {"en": q_en, "ar": q_ar},
                                 "answer": {"en": answers["en"][key], "ar": answers["ar"][key]}})
    return out


def _answers(env: Environment, c: dict[str, Any], rec: dict[str, Any], lang: str) -> dict[str, str]:
    ar = lang == "ar"
    res, op, biz, ev = c["res"], c["op"], c["business"], c["ev"]
    elim, mit = len(res["paths_eliminated"]), len(res["paths_mitigated"])
    pb, pa = c["before"]["posture_score"], c["after"]["posture_score"]
    base_n, rem_n = c["before"]["attack_paths"], c["after"]["attack_paths"]
    subj = action_label(env, c["action"], lang)
    assets = _list([_n(env, a, lang) for a in op["affected_assets"]], lang)
    lvl = SEV[lang][op["level"]]
    ev_txt = _list([f"{ev[k]} {EVC[lang][k]}" for k in ("validated", "observed", "inferred", "theoretical") if ev[k]], lang) or ("—")
    srcs = _list(c["sources"], lang, 4) or "—"
    conf = CONF[lang][c["confidence"]]
    reasons = "؛ ".join(_conf_reason(r, lang) for r in c["confidence_reasons"]) if ar else "; ".join(_conf_reason(r, lang) for r in c["confidence_reasons"])

    # business
    if biz["services_declared"] == 0:
        biz_services = ("لم تُعرَّف خدمات أعمال في هذه البيئة، لذا لا يمكن تقدير الأثر على الخدمات." if ar
                        else "No business services are declared in this environment, so service impact cannot be estimated.")
    elif not biz["services"]:
        biz_services = ("لا تعتمد أي خدمة معرَّفة على العلاقات المتأثرة." if ar else "No declared service depends on the touched access.")
    else:
        parts = [f"{(s['name_ar'] if ar else s['name'])} ({EFFECT[lang][s['effect']]})" for s in biz["services"]]
        biz_services = (f"الخدمات المتأثرة: {_list(parts, lang)}. مؤشر أثر الأعمال {biz['business_impact_index']} من 100."
                        if ar else f"Services affected: {_list(parts, lang)}. Business-impact index {biz['business_impact_index']}/100.")
        if biz["rto_exceeded"] or biz["rto_unknown"]:
            biz_services += (f" تحذير: زمن الاسترجاع قد يتجاوز هدف التعافي في {biz['rto_exceeded']} خدمة، وغير معروف في {biz['rto_unknown']}."
                             if ar else f" Warning: recovery may exceed the recovery-time objective for {biz['rto_exceeded']} service(s) and is unknown for {biz['rto_unknown']}.")
    lost = len(op["lost_access"])
    lost_txt = (f"ستفقد هويات مشروعة وصولها إلى {lost} من الأصول." if ar else f"Legitimate identities would lose access in {lost} case(s).") if lost else (
        "لا يُفقد أي وصول مشروع." if ar else "No legitimate access is lost.")

    # residual
    if c["remaining"]:
        top = c["remaining"][0]
        res_extra = (f" أعلى مسار متبقٍّ: {top['score']} ({SEV[lang][top['severity']]}، {EVC[lang][top['classification']]})." if ar
                     else f" Highest remaining path: {top['score']} ({SEV[lang][top['severity']]}, {EVC[lang][top['classification']]}).")
    else:
        res_extra = " لا يتبقى أي مسار ضمن النموذج." if ar else " No path remains in the model."
    # approvals
    acts =SimulationRequest.model_validate({"actions": [c["action"]]}).actions
    roles = _list([ROLE[lang][a["role"]] for a in approvals_for(acts, op, biz)], lang)
    rev = (("قابل للتراجع بالكامل: يُعاد التفعيل أو تُستعاد الصلاحية السابقة." if ar else "Fully reversible: re-enable or restore the previous setting.")
           if op["fully_reversible"] else
           ("غير قابل للتراجع تلقائيًا: يلزم إعادة منح الصلاحية يدويًا ويجب التخطيط لذلك." if ar else "Not automatically reversible: the access must be re-granted manually, so plan for that."))
    partial = bool(c["before"].get("paths_truncated"))

    if ar:
        return {
            "proposed": f"{subj}.",
            "why": (f"أظهرت المحاكاة على نسخة معزولة إزالة {elim} من {base_n} مسار هجوم وإضعاف {mit}، وانخفض مؤشر الوضع الأمني من {pb} إلى {pa}. "
                    f"يمر {c['paths_through']} مسار عبر هذا الوصول."),
            "evidence": (f"المسارات المتأثرة {c['affected_paths']}: {ev_txt} (فئة أضعف حلقة). مستويات الأدلة يصرّح بها كاتب البيانات (المصادر: {srcs}) "
                         "ولا تتحقق منها أثر؛ والبيئة افتراضية، فلا شيء هنا مؤكَّد في العالم الحقيقي."),
            "confidence": f"الثقة {conf} (وسم استدلالي وليس احتمالًا). الأسباب: {reasons}.",
            "changes": f"يمسّ {len(op['affected_relationships'])} علاقة و{len(op['affected_assets'])} أصلًا: {assets}. {lost_txt}",
            "business": f"الأثر التشغيلي: {lvl}. {biz_services}",
            "residual": f"يتبقى {rem_n} مسارًا من أصل {base_n}.{res_extra}",
            "uncertainty": ("الدرجات مؤشرات استدلالية تعتمد على أوزان مفترضة وغير معايَرة؛ مستويات الأدلة مصرَّح بها ولم يتحقق منها أثر؛ "
                            "لا ترى أثر ضوابط لم تُدخَل في البيانات؛ ونتائج المحاكاة تخص النموذج لا الأنظمة الحقيقية."
                            + (" وبلغ عدّ المسارات حدّه الأقصى فالنتائج غير كاملة." if partial else "")),
            "approval": f"التوقيعات المطلوبة: {roles}. {rev} لا تنفّذ أثر أي تغيير بنفسها.",
        }
    return {
        "proposed": f"{subj}.",
        "why": (f"Simulation on an isolated copy eliminates {elim} of {base_n} attack paths and weakens {mit}; the posture index falls from {pb} to {pa}. "
                f"{c['paths_through']} path(s) pass through this access."),
        "evidence": (f"Affected paths ({c['affected_paths']}): {ev_txt} (weakest-link class). Evidence levels are declared by the data author "
                     f"(sources: {srcs}) and are not verified by ATHAR; the environment is synthetic, so nothing here is real-world validated."),
        "confidence": f"Confidence: {conf} (a heuristic label, not a probability). Reasons: {reasons}.",
        "changes": f"Touches {len(op['affected_relationships'])} relationship(s) and {len(op['affected_assets'])} asset(s): {assets}. {lost_txt}",
        "business": f"Operational impact: {lvl}. {biz_services}",
        "residual": f"{rem_n} of {base_n} attack paths remain.{res_extra}",
        "uncertainty": ("Scores are heuristic indices built on assumed, uncalibrated weights; evidence levels are declared and not verified by ATHAR; "
                        "ATHAR cannot see controls that were not entered; and results describe the model, not real systems."
                        + (" Path enumeration hit its cap, so results are incomplete." if partial else "")),
        "approval": f"Required sign-off: {roles}. {rev} ATHAR never applies a change itself.",
    }


