"""Reproducible results for the Meridian digital-twin scenario (the one used in the competition demo).

Run from the backend folder:  python ../scripts/meridian_report.py
Writes docs/evaluation/meridian.json and docs/evaluation/MERIDIAN.md. Everything is deterministic (seeded sensitivity), so a
second run is byte-identical; tests/test_docs.py pins the numbers quoted in COMPETITION_DEMO.md to meridian.json.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

os.environ.setdefault("ATHAR_DB", ":memory:")
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "backend"))

from app.analysis import DEFAULT_CONFIG, analyze  # noqa: E402
from app.data.scenario_meridian import build_meridian_environment  # noqa: E402
from app.evidence import evidence_overview  # noqa: E402
from app.plans import generate_plans  # noqa: E402
from app.recommendations import recommend_ex  # noqa: E402
from app.sensitivity import run_sensitivity  # noqa: E402
from datetime import datetime, timezone  # noqa: E402

NOW = datetime(2026, 11, 9, tzinfo=timezone.utc)      # fixed so the stale-evidence count is reproducible


def build() -> dict:
    env = build_meridian_environment()
    a = analyze(env)
    s = a["summary"]
    recs, partial = recommend_ex(env, a)
    plans = generate_plans(env, a)
    sens = run_sensitivity(env, DEFAULT_CONFIG, trials=16, spread=0.3, seed=1109)
    ev = evidence_overview(env, a, now=NOW)["summary"]
    return {
        "scenario": "meridian-enterprise",
        "assets": len([x for x in env.assets if x.type.value != "control"]), "relationships": len(env.relationships), "services": len(env.services),
        "baseline": {k: s[k] for k in ("attack_paths", "posture_score", "max_path_score", "validated_paths", "evidence_distribution", "severity_distribution")},
        "top_recommendation": {"id": recs[0]["id"], "paths_eliminated": recs[0]["paths_eliminated"], "priority": recs[0]["priority"], "impact": recs[0]["tradeoff"]},
        "recommendations_partial": partial,
        "plans": [{"id": p["id"], "strategy": p["strategy"], "actions": len(p["actions"]), "paths_after": p["metrics"]["paths_after"],
                   "posture_after": p["metrics"]["posture_after"], "disruption": p["disruption_cost"], "effort": p["effort"], "impact": p["operational"]["level"],
                   "reversible": p["operational"]["fully_reversible"], "services_interrupted": p["business"]["services_interrupted"],
                   "business_impact_index": p["business"]["business_impact_index"], "pareto": p["pareto"]["optimal"]} for p in plans["plans"]],
        "suggested_plan": plans["suggested_plan_id"],
        "sensitivity": {"trials": sens["trials"], "spread": sens["spread"], "posture": sens["posture"],
                        "top_recommendation_unchanged_pct": sens["top_recommendation_unchanged_pct"],
                        "highest_path_unchanged_pct": sens["highest_path_unchanged_pct"],
                        "most_influential": [p["name"] for p in sens["parameters"][:3]],
                        "top_rec_stability": sens["recommendations"][0]["stability"]},
        "evidence": {k: ev[k] for k in ("total", "by_evidence", "by_validation", "stale", "undated", "on_attack_paths", "weak_on_paths")},
    }


def markdown(r: dict) -> str:
    b, sv, ev = r["baseline"], r["sensitivity"], r["evidence"]
    L = ["# Meridian digital twin: generated results", "",
         "_Generated by `scripts/meridian_report.py` (deterministic). Synthetic data; heuristic indices, not probabilities._", "",
         f"{r['assets']} assets, {r['relationships']} relationships, {r['services']} business services.", "",
         f"**Baseline:** {b['attack_paths']} attack paths, posture {b['posture_score']}, highest path {b['max_path_score']}; "
         f"evidence classes {b['evidence_distribution']}; severities {b['severity_distribution']}.", "",
         f"**Top recommendation:** `{r['top_recommendation']['id']}` eliminates {r['top_recommendation']['paths_eliminated']} of {b['attack_paths']} paths "
         f"(priority {r['top_recommendation']['priority']}, impact {r['top_recommendation']['impact']}).", "",
         "## Plans", "", "| Plan | Actions | Paths left | Posture | Disruption | Effort | Impact | Reversible | Services interrupted | Pareto |", "|---|---|---|---|---|---|---|---|---|---|"]
    for p in r["plans"]:
        L.append(f"| {p['strategy']} | {p['actions']} | {p['paths_after']} | {p['posture_after']} | {p['disruption']} | {p['effort']} | {p['impact']} | "
                 f"{'yes' if p['reversible'] else 'no'} | {p['services_interrupted']} | {'yes' if p['pareto'] else 'no'} |")
    L += ["", f"Suggested starting point for human review: `{r['suggested_plan']}`. Pareto status is relative to these generated plans only; "
          "the plans come from greedy heuristics (plus one exact weighted cut), so no global optimality is claimed.", "",
          "## Sensitivity (weights varied by ±30%, 16 seeded trials)", "",
          f"- Posture index moves between {sv['posture']['min']} and {sv['posture']['max']} (baseline {sv['posture']['baseline']}).",
          f"- The top recommendation is unchanged in {sv['top_recommendation_unchanged_pct']}% of trials; the highest-scoring path in {sv['highest_path_unchanged_pct']}%.",
          f"- Most influential assumptions: {', '.join(sv['most_influential'])}.", "",
          "## Evidence", "",
          f"- {ev['total']} relationships: {ev['by_evidence']}; validation {ev['by_validation']} (none is real-world validated).",
          f"- {ev['stale']} older than 180 days at 2026-11-09, {ev['undated']} undated, {ev['on_attack_paths']} on attack paths, {ev['weak_on_paths']} of those with inferred or theoretical evidence.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    r = build()
    out = HERE.parent / "docs" / "evaluation"
    out.mkdir(parents=True, exist_ok=True)
    (out / "meridian.json").write_text(json.dumps(r, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    (out / "MERIDIAN.md").write_text(markdown(r), encoding="utf-8", newline="\n")
    print(markdown(r))
