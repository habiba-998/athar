"""Assemble the Hugging Face Space repository from this project.

    python scripts/make_hf_space.py --out build/hf-space [--force]

The Space is a DERIVED artifact (a Docker build context: Dockerfile, README with the Space settings, backend/app, the pinned runtime
requirements and the frontend sources). It contains no tests, no secrets, no database and no local files: only tracked project
files are copied (git ls-files), plus the three files in deploy/huggingface/. Re-running with --force replaces the previous output
(only if it carries the marker file this script writes). Pushing it to Hugging Face is a separate, authorised step
(see docs/DEPLOYMENT.md); this script never contacts the network.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = ".athar-hf-space"
# frontend files needed by `npm ci && npm run build` (tsconfig includes only src/ and vite.config.ts)
FRONTEND_KEEP = ("frontend/src/", "frontend/index.html", "frontend/package.json", "frontend/package-lock.json",
                 "frontend/tsconfig.json", "frontend/vite.config.ts")
BACKEND_KEEP = ("backend/app/", "backend/requirements.prod.txt")
SKIP_PARTS = {"__pycache__", "node_modules", "dist"}


def tracked(prefixes: tuple[str, ...]) -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split("\0")
    return sorted(f for f in out if f and f.startswith(prefixes) and not SKIP_PARTS & set(Path(f).parts) and not f.endswith(".pyc"))


def build(out: Path, force: bool = False) -> list[str]:
    if out.exists() and any(out.iterdir()):
        if not force:
            raise SystemExit(f"{out} is not empty; use --force to replace a previous build")
        if not (out / MARKER).exists():
            raise SystemExit(f"{out} was not created by this script (no {MARKER}); refusing to delete it")
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)
    copied = []
    for rel in tracked(BACKEND_KEEP + FRONTEND_KEEP):
        dest = out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / rel, dest)
        copied.append(rel)
    for src, name in (("Dockerfile", "Dockerfile"), ("README.md", "README.md"), ("dockerignore.txt", ".dockerignore")):
        shutil.copyfile(ROOT / "deploy" / "huggingface" / src, out / name)
        copied.append(name)
    (out / MARKER).write_text("generated by scripts/make_hf_space.py; safe to delete\n", encoding="utf-8")
    return copied


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="directory to create (must be empty or a previous build with --force)")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    files = build(Path(a.out).resolve(), a.force)
    print(f"assembled {len(files)} files into {Path(a.out).resolve()}")
