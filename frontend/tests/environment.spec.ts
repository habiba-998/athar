import { expect, load, openTab, test } from './helpers'

const sampleJson = async (api: import('@playwright/test').APIRequestContext) => (await api.get('/api/environment')).json()

const upload = (page: import('@playwright/test').Page, content: string, name = 'env.json') =>
  page.getByTestId('import-input').setInputFiles({ name, mimeType: 'application/json', buffer: Buffer.from(content) })

test('import a valid environment, see it re-analysed, then restore the sample', async ({ page, api }) => {
  const env = await sampleJson(api)
  env.name = 'Imported Corp'
  env.relationships = env.relationships.filter((r: { id: string }) => r.id !== 'r03') // removes the jump-host shortcut
  await load(page)
  await openTab(page, 'Environment')
  await expect(page.getByTestId('env-kind')).toContainText('Sample environment')
  await upload(page, JSON.stringify(env))
  await expect(page.getByTestId('env-notice')).toContainText('Environment imported')
  await expect(page.getByTestId('env-kind')).toContainText('Custom environment')
  expect((await (await api.get('/api/environment')).json()).name).toBe('Imported Corp')
  expect((await (await api.get('/api/analysis')).json()).summary.attack_paths).toBe(11)
  await openTab(page, 'Dashboard')
  await expect(page.getByTestId('kpis')).toContainText('11')
  await openTab(page, 'Environment')
  await page.getByRole('button', { name: 'Load sample' }).click()
  await expect(page.getByTestId('env-notice')).toContainText('Sample environment restored')
  await expect(page.getByTestId('env-kind')).toContainText('Sample environment')
  expect((await (await api.get('/api/analysis')).json()).summary.attack_paths).toBe(20)
})

test('import rejects dangling references, shows the reason and changes nothing', async ({ page, api }) => {
  const env = await sampleJson(api)
  env.relationships[0].target = 'ghost-asset'
  const before = await (await api.get('/api/environment')).json()
  await load(page)
  await openTab(page, 'Environment')
  await upload(page, JSON.stringify(env))
  const notice = page.getByTestId('env-notice')
  await expect(notice).toContainText('The file was rejected')
  await expect(notice).toContainText('unknown asset')
  await expect(page.getByRole('alert')).toBeVisible()
  expect(await (await api.get('/api/environment')).json()).toEqual(before)
})

test('import rejects non-JSON, wrong shape and oversize files', async ({ page, api }) => {
  const before = await (await api.get('/api/environment')).json()
  await load(page)
  await openTab(page, 'Environment')
  await upload(page, 'this is not json')
  await expect(page.getByTestId('env-notice')).toContainText('not valid JSON')
  await upload(page, JSON.stringify({ hello: 'world' }))
  await expect(page.getByTestId('env-notice')).toContainText('The file was rejected')
  await upload(page, 'x'.repeat(1_100_000))
  await expect(page.getByTestId('env-notice')).toContainText('larger than 1 MB')
  expect(await (await api.get('/api/environment')).json()).toEqual(before)
})

test('add, edit and delete an asset; invalid input is rejected by the server', async ({ page, api }) => {
  await load(page)
  await openTab(page, 'Environment')
  await page.getByRole('button', { name: 'Add asset' }).click()
  const form = page.getByRole('form', { name: 'Add asset' })
  await form.getByLabel('ID (lowercase letters, digits, - _)').fill('new-db')
  await form.getByLabel('Name (English)').fill('Analytics DB')
  await form.getByLabel('Name (Arabic)').fill('قاعدة التحليلات')
  await form.getByLabel('Type').selectOption('database')
  await form.getByLabel('Criticality (1–5)').fill('5')
  await form.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByTestId('env-notice')).toContainText('Saved and re-analysed')
  await expect(page.getByTestId('asset-table')).toContainText('Analytics DB')
  expect((await (await api.get('/api/environment')).json()).assets.some((a: { id: string }) => a.id === 'new-db')).toBe(true)

  // duplicate id: server rejects, the form shows the reason, the list does not change
  await page.getByRole('button', { name: 'Add asset' }).click()
  const dup = page.getByRole('form', { name: 'Add asset' })
  await dup.getByLabel('ID (lowercase letters, digits, - _)').fill('new-db')
  await dup.getByLabel('Name (English)').fill('Dup')
  await dup.getByLabel('Name (Arabic)').fill('مكرر')
  await dup.getByRole('button', { name: 'Save' }).click()
  await expect(dup.getByRole('alert')).toContainText('duplicate asset id')
  await dup.getByRole('button', { name: 'Cancel' }).click()

  await page.getByRole('button', { name: 'Edit: Analytics DB' }).click()
  const edit = page.getByRole('form', { name: 'Edit' })
  await expect(edit.getByLabel('ID (lowercase letters, digits, - _)')).toBeDisabled()
  await edit.getByLabel('Name (English)').fill('Analytics Warehouse')
  await edit.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByTestId('asset-table')).toContainText('Analytics Warehouse')

  await page.getByRole('button', { name: 'Delete: Analytics Warehouse' }).click()
  await page.getByRole('button', { name: 'Confirm delete: Analytics Warehouse' }).click()
  await expect(page.getByTestId('env-notice')).toContainText('Deleted')
  await expect(page.getByTestId('asset-table')).not.toContainText('Analytics Warehouse')
})

test('add a relationship that creates a new attack path; reject one with a self-loop', async ({ page, api }) => {
  const base = (await (await api.get('/api/analysis')).json()).summary.attack_paths
  await load(page)
  await openTab(page, 'Environment')
  await page.getByRole('tab', { name: /Relationships/ }).click()
  await page.getByRole('button', { name: 'Add relationship' }).click()
  const form = page.getByRole('form', { name: 'Add relationship' })
  await form.getByLabel('ID (lowercase letters, digits, - _)').fill('r90')
  await form.getByLabel('Source').selectOption('emp-sara')
  await form.getByLabel('Target').selectOption('db-hr')
  await form.getByLabel('Relationship type').selectOption('read_access')
  await form.getByLabel('Privilege').selectOption('read')
  await form.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByTestId('rel-table')).toContainText('r90')
  expect((await (await api.get('/api/analysis')).json()).summary.attack_paths).toBeGreaterThan(base)

  await page.getByRole('button', { name: 'Add relationship' }).click()
  const bad = page.getByRole('form', { name: 'Add relationship' })
  await bad.getByLabel('ID (lowercase letters, digits, - _)').fill('r91')
  await bad.getByLabel('Source').selectOption('emp-omar')
  await bad.getByLabel('Target').selectOption('emp-omar')
  await bad.getByRole('button', { name: 'Save' }).click()
  await expect(bad.getByRole('alert')).toContainText('self-loop')
})

